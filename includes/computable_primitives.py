def insert_at_end_of_list(item, list):
    list.append(item)
    return list

def clear_list(list):
    list = []
    return list

def equals(value1, value2):
    return value1 == value2

def not_equals(value1, value2):
    return value1 != value2

def multiply(multiplicand, multiplier):
    return multiplicand * multiplier

def get_length(list):
    return len(list)

def cast_num_to_string(num):
    return str(num)